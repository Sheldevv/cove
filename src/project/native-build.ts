import { readFile, mkdir, writeFile } from "node:fs/promises";
import { dirname, basename, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { compileToC } from "../compiler/compile.js";
import { IRCEmitter } from "../compiler/ir-c-emitter.js";
import type { IRModule } from "../compiler/ir.js";
import type { LoadedProject, CoveTarget } from "./config.js";
import { resolveProjectPath, ProjectConfigError } from "./config.js";
import type { DiscoveredSources } from "./discovery.js";
import type { ModuleGraph } from "./modules.js";
import { combineProjectSources, moduleNameForSource } from "./modules.js";

export interface ProjectNativeResult { readonly success: boolean; readonly compiler: string; readonly output: string; readonly generated: readonly string[]; readonly diagnostics: readonly string[]; }
const run = (command: string, args: string[]) => spawnSync(command, args, { encoding: "utf8" });
function functionNames(source: string): string[] {
  const names = new Set<string>();
  const re = /(?:\bfun\s+|\b(?:void|bool|char|short|int|long|float|double|String|Int|Float|Double|Bool)\s+)([A-Za-z_][A-Za-z0-9_]*)\s*\(/g;
  for (const match of source.matchAll(re)) names.add(match[1]!);
  return [...names];
}
function compilerFor(requested: string): string {
  const candidates = requested !== "auto" ? [requested] : process.env.CC ? [process.env.CC, "gcc", "clang"] : ["gcc", "clang"];
  for (const candidate of candidates) if (!run(candidate, ["--version"]).error && run(candidate, ["--version"]).status === 0) return candidate;
  throw new ProjectConfigError("No working C compiler found; install GCC or Clang or configure compiler.c");
}
export async function buildProjectNative(project: LoadedProject, target: CoveTarget, sources: DiscoveredSources, graph: ModuleGraph): Promise<ProjectNativeResult> {
  const build = resolveProjectPath(project, project.config.paths.build);
  const generatedDir = resolve(build, "generated"), objectDir = resolve(build, "obj");
  await mkdir(generatedDir, { recursive: true }); await mkdir(objectDir, { recursive: true });
  const combined = await combineProjectSources(project, graph, target.entry ? resolveProjectPath(project, target.entry) : undefined);
  const compiled = compileToC({ path: combined.path, text: combined.text });
  const diagnostics = compiled.diagnostics.items.map((d) => `${d.code}: ${d.message}`);
  if (!compiled.irModule || compiled.diagnostics.hasErrors) return { success: false, compiler: "", output: "", generated: [], diagnostics };
  const ir = compiled.irModule as IRModule;
  const emitter = new IRCEmitter();
  const moduleFunctions = new Map<string, Set<string>>();
  for (const source of graph.order) {
    const text = await readFile(source, "utf8");
    moduleFunctions.set(source, new Set(functionNames(text)));
  }
  const assigned = new Set<string>();
  for (const set of moduleFunctions.values()) for (const name of set) {
    if (assigned.has(name)) throw new ProjectConfigError(`Duplicate function '${name}' across Cove modules; separate compilation requires unique external function names`);
    assigned.add(name);
  }
  const moduleHeaders: string[] = [];
  const generated: string[] = [];
  const objects: string[] = [];
  const allHeaders = graph.order.map((source) => `${moduleNameForSource(source, project).replace(/[^A-Za-z0-9_]/g, "_")}.h`);
  // Emit every interface before compiling any translation unit so include order is irrelevant.
  for (const source of graph.order) {
    const moduleName = moduleNameForSource(source, project).replace(/[^A-Za-z0-9_]/g, "_");
    const names = moduleFunctions.get(source)!;
    const funcs = ir.functions.filter((fn) => names.has(fn.name));
    if (!funcs.length) continue;
    const guard = `COVE_${moduleName.toUpperCase()}_H`;
    const text = ["/* Generated by Cove. */", `#ifndef ${guard}`, `#define ${guard}`, ...funcs.map((fn) => emitter.declaration(fn)), "#endif", ""].join("\n");
    await writeFile(resolve(generatedDir, `${moduleName}.h`), text);
  }
  for (const source of graph.order) {
    const moduleName = moduleNameForSource(source, project).replace(/[^A-Za-z0-9_]/g, "_");
    const names = moduleFunctions.get(source)!;
    const funcs = ir.functions.filter((fn) => names.has(fn.name));
    if (!funcs.length) continue;
    const header = `${moduleName}.h`, cFile = `${moduleName}.c`, object = `${moduleName}.o`;
    const headerText = ["/* Generated by Cove. */", `#ifndef COVE_${moduleName.toUpperCase()}_H`, `#define COVE_${moduleName.toUpperCase()}_H`, ...funcs.map((fn) => emitter.declaration(fn)), "#endif", ""].join("\n");
    await writeFile(resolve(generatedDir, header), headerText);
    const selected = new Set(funcs.map((fn) => fn.name));
    const includes = [...allHeaders.filter((h) => h !== header), ...(graph.nativeHeaders.get(source) ?? [])];
    const cText = emitter.emit({ kind: "IRModule", functions: funcs }, selected, includes);
    await writeFile(resolve(generatedDir, cFile), cText);
    const objectPath = resolve(objectDir, object);
    const cc = compilerFor(project.config.compiler.c);
    const args = [`-std=${project.config.compiler.standard}`, "-Wall", "-Wextra", `-${project.config.compiler.optimization}`, "-fPIC", ...project.config.compiler.flags, ...project.config.compiler.includeDirs.map((d) => `-I${resolveProjectPath(project, d)}`), ...target.includeDirs.map((d) => `-I${resolveProjectPath(project, d)}`), `-I${generatedDir}`, "-c", resolve(generatedDir, cFile), "-o", objectPath];
    const result = run(cc, args); if (result.status !== 0) diagnostics.push(result.stderr || result.stdout || `Failed compiling ${cFile}`);
    objects.push(objectPath); generated.push(resolve(generatedDir, cFile), resolve(generatedDir, header));
  }
  const cc = compilerFor(project.config.compiler.c);
  for (const cSource of sources.c) {
    const objectName = cSource.slice(project.root.length + 1).replace(/\.[^.]+$/, "").replace(/[^A-Za-z0-9_]+/g, "_");
    const objectPath = resolve(objectDir, `${objectName}.o`);
    const result = run(cc, [`-std=${project.config.compiler.standard}`, ...project.config.compiler.flags, ...project.config.compiler.includeDirs.map((d) => `-I${resolveProjectPath(project, d)}`), ...target.includeDirs.map((d) => `-I${resolveProjectPath(project, d)}`), `-I${resolve(project.root, project.config.paths.include[0] ?? "include")}`, "-fPIC", "-c", cSource, "-o", objectPath]);
    if (result.status !== 0) diagnostics.push(result.stderr || result.stdout || `Failed compiling ${cSource}`);
    objects.push(objectPath);
  }
  if (diagnostics.length) return { success: false, compiler: cc, output: "", generated, diagnostics };
  const output = resolve(project.root, project.config.paths.build, target.output);
  await mkdir(dirname(output), { recursive: true });
  const libDirs = [...project.config.compiler.libraryDirs, ...target.libraryDirs].map((d) => `-L${resolveProjectPath(project, d)}`);
  const libraries = [...project.config.compiler.libraries, ...target.libraries].map((lib) => `-l${lib}`);
  const linkFlags = [...project.config.compiler.linkerFlags, ...libDirs, ...libraries];
  let result;
  if (target.type === "object") {
    return { success: true, compiler: cc, output: objectDir, generated, diagnostics };
  } else if (target.type === "static") {
    const ar = run("ar", ["rcs", output.endsWith(".a") ? output : `${output}.a`, ...objects]);
    result = ar;
  } else {
    const shared = target.type === "shared";
    result = run(cc, [...(shared ? ["-shared"] : []), ...objects, ...linkFlags, "-o", output]);
  }
  if (result.status !== 0) diagnostics.push(result.stderr || result.stdout || "Native link failed");
  return { success: result.status === 0, compiler: cc, output: target.type === "static" && !output.endsWith(".a") ? `${output}.a` : output, generated, diagnostics };
}
