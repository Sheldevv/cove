import type { DiagnosticBag } from "../diagnostics/diagnostic.js";
import type { SourceFile } from "../diagnostics/source.js";
import type {
  AssignmentExpression, BinaryExpression, BlockStatement, CallExpression, Declaration,
  Expression, FunctionDeclaration, IfStatement, Parameter, Program, Statement, TypeNode,
  VariableDeclaration, WhileStatement,
} from "../parser/ast.js";
import type { CoveType, TypedProgram } from "./typed-ir.js";

interface Binding { cType: string; kind: "string" | "int" | "double" | "bool" | "unknown"; }

/** Emits a single readable C translation unit. Multi-module emission is a later milestone. */
export class CEmitter {
  private readonly lines: string[] = [];
  private typed!: TypedProgram;
  private indentLevel = 0;

  constructor(private readonly file: SourceFile, private readonly diagnostics: DiagnosticBag) {}

  emit(typed: TypedProgram): string {
    this.typed = typed;
    const program = typed.ast;
    this.lines.push("/* Generated by Cove. Do not edit. */", "#include <stdbool.h>", "#include <stdio.h>", "#include <stdlib.h>", "#include <string.h>", "");
    const functions = program.declarations.filter((d): d is FunctionDeclaration => d.kind === "FunctionDeclaration");
    const names = new Set<string>();
    if (!functions.some((fn) => fn.name === "main")) {
      this.diagnostics.error("COV3007", "an executable Cove program must define fun main()", this.file, program.span);
    }
    for (const fn of functions) {
      if (names.has(fn.name)) this.diagnostics.error("COV3001", `duplicate function '${fn.name}'`, this.file, fn.span);
      names.add(fn.name);
      if (fn.name === "print") this.diagnostics.error("COV3002", "'print' is a reserved Cove built-in name", this.file, fn.span);
      for (const parameter of fn.parameters) {
        if (!parameter.type) this.diagnostics.error("COV3010", `parameter '${parameter.name}' needs an explicit type in this backend prototype`, this.file, parameter.span);
      }
    }
    // Emit prototypes first so functions can call declarations that appear later in the file.
    for (const fn of functions) {
      const returnBinding = fn.name === "main"
        ? { cType: "int", kind: "int" as const }
        : this.bindingForType(this.typed.functionReturnTypes.get(fn) ?? "Unknown");
      const params = fn.parameters.length === 0
        ? "void"
        : fn.parameters.map((p) => this.formatDeclarator(this.bindingForParameter(p).cType, p.name)).join(", ");
      this.lines.push(`${this.formatDeclarator(returnBinding.cType, fn.name)}(${params});`);
    }
    this.lines.push("");
    // This helper is inline and harmless when a program does not concatenate strings.
    this.lines.push(
      "typedef struct CoveStringAllocation {",
      "    char *value;",
      "    struct CoveStringAllocation *next;",
      "} CoveStringAllocation;",
      "static CoveStringAllocation *cove_string_allocations = NULL;",
      "static void cove_cleanup_strings(void) {",
      "    CoveStringAllocation *item = cove_string_allocations;",
      "    while (item != NULL) {",
      "        CoveStringAllocation *next = item->next;",
      "        free(item->value);",
      "        free(item);",
      "        item = next;",
      "    }",
      "    cove_string_allocations = NULL;",
      "}",
      "static inline char *cove_concat(const char *left, const char *right) {",
      "    size_t a = strlen(left), b = strlen(right);",
      "    char *result = (char *)malloc(a + b + 1);",
      "    if (result == NULL) return NULL;",
      "    memcpy(result, left, a);",
      "    memcpy(result + a, right, b + 1);",
      "    CoveStringAllocation *item = (CoveStringAllocation *)malloc(sizeof(*item));",
      "    if (item == NULL) { free(result); return NULL; }",
      "    item->value = result;",
      "    item->next = cove_string_allocations;",
      "    cove_string_allocations = item;",
      "    static bool cleanup_registered = false;",
      "    if (!cleanup_registered) { atexit(cove_cleanup_strings); cleanup_registered = true; }",
      "    return result;",
      "}",
      "",
    );
    for (const declaration of program.declarations) {
      if (declaration.kind === "FunctionDeclaration") this.emitFunction(declaration);
      else this.reportUnsupported(declaration, "top-level statements are not supported by the C backend yet");
    }
    return `${this.lines.join("\n")}\n`;
  }

  private emitFunction(fn: FunctionDeclaration): void {
    const isMain = fn.name === "main";
    const returnType = isMain ? "int" : this.bindingForType(this.typed.functionReturnTypes.get(fn) ?? "Unknown").cType;
    const params = fn.parameters.length === 0
      ? "void"
      : fn.parameters.map((p) => this.formatDeclarator(this.bindingForParameter(p).cType, p.name)).join(", ");
    this.write(`${this.formatDeclarator(returnType, fn.name)}(${params}) {`);
    this.indentLevel++;
    const statements = fn.body.statements;
    const last = statements[statements.length - 1];
    const hasValueReturn = !isMain && returnType !== "void";
    if (hasValueReturn && last?.kind === "ExpressionStatement") {
      this.emitStatements(statements.slice(0, -1));
      this.write(`return ${this.emitExpression(last.expression)};`);
    } else {
      this.emitStatements(statements);
      if (isMain) this.write("return 0;");
    }
    this.indentLevel--;
    this.write("}");
    this.write("");
  }

  private emitStatements(statements: Statement[]): void {
    for (const statement of statements) this.emitStatement(statement);
  }

  private emitStatement(statement: Statement): void {
    switch (statement.kind) {
      case "BlockStatement": this.emitBlock(statement); break;
      case "VariableDeclaration": this.emitVariable(statement); break;
      case "ReturnStatement":
        this.write(statement.value ? `return ${this.emitExpression(statement.value)};` : "return;");
        break;
      case "ExpressionStatement": this.write(`${this.emitExpression(statement.expression)};`); break;
      case "IfStatement": this.emitIf(statement); break;
      case "WhileStatement": this.emitWhile(statement); break;
      case "ForEachStatement": this.write(`for (size_t __i = 0; __i < (${this.emitExpression(statement.iterable)}).length; ++__i) { ${this.bindingForType(this.typed.expressionTypes.get(statement.iterable)?.match(/^Array<(.+)>$/)?.[1] ?? "Unknown").cType} ${statement.variable} = (${this.emitExpression(statement.iterable)}).data[__i];`); this.indentLevel++; this.emitStatement(statement.body); this.indentLevel--; this.write("}"); break;
    }
  }

  private emitBlock(block: BlockStatement): void {
    this.write("{");
    this.indentLevel++;
    this.emitStatements(block.statements);
    this.indentLevel--;
    this.write("}");
  }

  private emitVariable(variable: VariableDeclaration): void {
    const binding = this.bindingForType(this.typed.variableTypes.get(variable) ?? "Unknown");
    const initializer = variable.initializer ? ` = ${this.emitExpression(variable.initializer)}` : "";
    this.write(`${this.formatDeclarator(binding.cType, variable.name)}${initializer};`);
  }

  private emitIf(statement: IfStatement): void {
    this.write(`if (${this.emitExpression(statement.condition)})`);
    this.emitControlledStatement(statement.thenBranch);
    if (statement.elseBranch) {
      this.write("else");
      this.emitControlledStatement(statement.elseBranch);
    }
  }

  private emitWhile(statement: WhileStatement): void {
    this.write(`while (${this.emitExpression(statement.condition)})`);
    this.emitControlledStatement(statement.body);
  }

  private emitControlledStatement(statement: Statement): void {
    if (statement.kind === "BlockStatement") this.emitBlock(statement);
    else {
      this.indentLevel++;
      this.emitStatement(statement);
      this.indentLevel--;
    }
  }

  private emitExpression(expression: Expression): string {
    switch (expression.kind) {
      case "LiteralExpression":
        if (typeof expression.value === "string") return this.cString(expression.value);
        if (typeof expression.value === "boolean") return expression.value ? "true" : "false";
        if (expression.value === null) return "NULL";
        return String(expression.value);
      case "IdentifierExpression": return expression.name;
      case "GroupExpression": return `(${this.emitExpression(expression.expression)})`;
      case "UnaryExpression": return `(${expression.operator}${this.emitExpression(expression.operand)})`;
      case "BinaryExpression": return this.emitBinary(expression);
      case "AssignmentExpression": return this.emitAssignment(expression);
      case "ArrayLiteralExpression": return `(CoveArrayInt){ .data = (const long long[]){ ${expression.elements.map((item) => this.emitExpression(item)).join(", ")} }, .length = ${expression.elements.length} }`;
      case "IndexExpression": return `(${this.emitExpression(expression.target)}).data[(size_t)(${this.emitExpression(expression.index)})]`;
      case "CallExpression": return this.emitCall(expression);
    }
  }

  private emitBinary(expression: BinaryExpression): string {
    if (expression.operator === "+" && this.expressionKind(expression.left) === "string" && this.expressionKind(expression.right) === "string") {
      return `cove_concat(${this.emitExpression(expression.left)}, ${this.emitExpression(expression.right)})`;
    }
    return `(${this.emitExpression(expression.left)} ${expression.operator} ${this.emitExpression(expression.right)})`;
  }

  private emitAssignment(expression: AssignmentExpression): string {
    return `(${this.emitExpression(expression.target)} ${expression.operator ?? "="} ${this.emitExpression(expression.value)})`;
  }

  private emitCall(expression: CallExpression): string {
    if (expression.callee.kind === "IdentifierExpression" && expression.callee.name === "print") {
      if (expression.arguments.length !== 1) {
        this.diagnostics.error("COV3004", "print() currently expects exactly one argument", this.file, expression.span);
        return "(void)0";
      }
      const argument = expression.arguments[0]!;
      const kind = this.expressionKind(argument);
      const value = this.emitExpression(argument);
      if (kind === "unknown") {
        this.diagnostics.error("COV3009", "cannot determine the type of this print() argument yet", this.file, argument.span, "Print a string, integer, floating-point value, or boolean.");
        return "(void)0";
      }
      if (kind === "string") return `printf("%s\\n", ${value})`;
      if (kind === "double") return `printf("%g\\n", (double)(${value}))`;
      if (kind === "bool") return `printf("%s\\n", (${value}) ? "true" : "false")`;
      return `printf("%lld\\n", (long long)(${value}))`;
    }
    return `${this.emitExpression(expression.callee)}(${expression.arguments.map((arg) => this.emitExpression(arg)).join(", ")})`;
  }

  private expressionKind(expression: Expression): Binding["kind"] {
    const type = this.typed.expressionTypes.get(expression) ?? "Unknown";
    switch (type) {
      case "String": return "string";
      case "Bool": return "bool";
      case "Float": case "Double": return "double";
      case "Int": return "int";
      default: return "unknown";
    }
  }

  private bindingForParameter(parameter: Parameter): Binding {
    return this.bindingForType(this.typed.parameterTypes.get(parameter) ?? "Unknown");
  }

  private bindingForType(type: CoveType): Binding {
    switch (type) {
      case "String": return { cType: "const char *", kind: "string" };
      case "Float": return { cType: "float", kind: "double" };
      case "Double": return { cType: "double", kind: "double" };
      case "Bool": return { cType: "bool", kind: "bool" };
      case "Int": return { cType: "long long", kind: "int" };
      case "Void": return { cType: "void", kind: "unknown" };
      case "Null": return { cType: "void *", kind: "unknown" };
      case "Unknown": return { cType: "long long", kind: "unknown" };
      default: return { cType: "long long", kind: "unknown" };
    }
  }


  private formatDeclarator(cType: string, name: string): string { return `${cType}${cType.endsWith("*") ? "" : " "}${name}`; }
  private cString(value: string): string { return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n").replace(/\r/g, "\\r").replace(/\t/g, "\\t").replace(/\0/g, "\\0")}"`; }
  private reportUnsupported(declaration: Declaration, message: string): void { this.diagnostics.error("COV3006", message, this.file, declaration.span); }
  private write(line: string): void { this.lines.push(`${"    ".repeat(this.indentLevel)}${line}`); }
}
