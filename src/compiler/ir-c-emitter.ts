import type { CoveType } from "./typed-ir.js";
import type { IRFunction, IRInstruction, IRModule, IROperand, IRValue } from "./ir.js";
import { resolveRuntimeRequirements } from "./runtime.js";

/** C backend for explicit IR. It has no dependency on parser AST nodes. */
export class IRCEmitter {
  emit(module: IRModule, selectedNames?: ReadonlySet<string>, headerIncludes: readonly string[] = []): string {
    const functions = selectedNames ? module.functions.filter((fn) => selectedNames.has(fn.name)) : module.functions;
    const selectedModule: IRModule = { kind: "IRModule", functions };
    const runtime = resolveRuntimeRequirements(selectedModule);
    const arrayTypes = this.collectArrayTypes(selectedModule);
    const lines = ["/* Generated by Cove from explicit IR. Do not edit. */"];
    for (const include of runtime.cHeaders) lines.push(`#include ${include}`);
    for (const include of headerIncludes) lines.push(include.startsWith("<") ? `#include ${include}` : `#include "${include}"`);
    if (arrayTypes.length) lines.push("#include <stddef.h>");
    if (runtime.cHeaders.length || headerIncludes.length || arrayTypes.length) lines.push("");
    for (const arrayType of arrayTypes) lines.push(this.arrayTypedef(arrayType));
    if (arrayTypes.length) lines.push("");
    for (const fn of module.functions) lines.push(`${(fn.name === "main" ? "int" : this.type(fn.returnType))} ${fn.name}(${fn.parameters.length ? fn.parameters.map((p) => `${this.type(p.type)} v${p.value.id}`).join(", ") : "void"});`);
    lines.push("");
    for (const fragment of runtime.fragments) lines.push(fragment, "");
    for (const fn of functions) this.emitFunction(lines, fn);
    return `${lines.join("\n")}\n`;
  }
  declaration(fn: IRFunction): string { return `${(fn.name === "main" ? "int" : this.type(fn.returnType))} ${fn.name}(${fn.parameters.length ? fn.parameters.map((p) => `${this.type(p.type)} v${p.value.id}`).join(", ") : "void"});`; }
  private emitFunction(out: string[], fn: IRFunction): void {
    out.push(`${(fn.name === "main" ? "int" : this.type(fn.returnType))} ${fn.name}(${fn.parameters.length ? fn.parameters.map((p) => `${this.type(p.type)} v${p.value.id}`).join(", ") : "void"}) {`);
    const parameterIds = new Set(fn.parameters.map((p) => p.value.id));
    const values = new Map<number, CoveType>();
    const slots = new Map<number, CoveType>();
    for (const block of fn.blocks) for (const ins of block.instructions) {
      if (ins.op === "alloca") slots.set(ins.result.id, ins.result.type);
      else if ("result" in ins && ins.result) values.set(ins.result.id, ins.result.type);
    }
    for (const [id, type] of values) if (!parameterIds.has(id)) out.push(`    ${this.type(type)} v${id};`);
    const blockIds = new Map(fn.blocks.map((block, index) => [block.name, index]));
    const hasPhi = fn.blocks.some((block) => block.instructions.some((ins) => ins.op === "phi"));
    if (hasPhi) out.push("    int __cove_pred = -1;");
    for (const [id, type] of slots) out.push(`    ${this.type(type)} slot${id};`);
    const targets = new Set<string>();
    for (const block of fn.blocks) for (const ins of block.instructions) {
      if (ins.op === "jump") targets.add(ins.target);
      if (ins.op === "branch") { targets.add(ins.thenBlock); targets.add(ins.elseBlock); }
    }
    for (const block of fn.blocks) {
      if (targets.has(block.name)) out.push(`${block.name}:;`);
      for (const ins of block.instructions) {
        if (ins.op === "phi") {
          const entries = ins.incoming;
          entries.forEach((entry, index) => {
            const condition = `__cove_pred == ${blockIds.get(entry.block) ?? -2}`;
            out.push(`    ${index === 0 ? "if" : "else if"} (${condition}) v${ins.result.id} = ${this.operand(entry.value)};`);
          });
        } else if (ins.op === "jump") {
          if (hasPhi) out.push(`    __cove_pred = ${blockIds.get(block.name) ?? -1};`);
          out.push(`    goto ${ins.target};`);
        } else if (ins.op === "branch") {
          out.push(hasPhi ? `    if (${this.operand(ins.condition)}) { __cove_pred = ${blockIds.get(block.name) ?? -1}; goto ${ins.thenBlock}; } else { __cove_pred = ${blockIds.get(block.name) ?? -1}; goto ${ins.elseBlock}; }` : `    if (${this.operand(ins.condition)}) goto ${ins.thenBlock}; else goto ${ins.elseBlock};`);
        } else out.push(`    ${this.instruction(ins)}`);
      }
    }
    out.push("}", "");
  }
  private operand(o: IROperand): string {
    if (o.kind === "value") return `v${o.value.id}`;
    if (o.kind === "string") return this.string(String(o.value));
    if (o.kind === "bool") return o.value ? "true" : "false";
    if (o.kind === "null") return "NULL";
    return `${String(o.value)}${o.type === "Float" && o.kind === "float" ? "f" : ""}`;
  }
  private instruction(i: IRInstruction): string {
    const op = (o: IROperand): string => this.operand(o);
    switch (i.op) {
      case "const": return `v${i.result.id} = ${op(i.value)};`;
      case "copy": return `v${i.result.id} = ${op(i.source)};`;
      case "phi": return `/* phi v${i.result.id} assigned on incoming edge */`;
      case "alloca": return "/* stack slot declared above */";
      case "load": return `v${i.result.id} = slot${i.slot.id};`;
      case "store": return `slot${i.slot.id} = ${op(i.source)};`;
      case "unary": return `v${i.result.id} = (${i.operator}${op(i.operand)});`;
      case "binary": return `v${i.result.id} = ${i.operator === "+" && i.result.type === "String" ? `cove_concat(${op(i.left)}, ${op(i.right)})` : `(${op(i.left)} ${i.operator} ${op(i.right)})`};`;
      case "call": return `${i.result ? `v${i.result.id} = ` : ""}${i.callee}(${i.args.map(op).join(", ")});`;
      case "array": {
        const elementType = this.arrayElement(i.result.type);
        const values = i.elements.map(op).join(", ");
        const data = i.elements.length ? `(${this.type(elementType)} const[]){ ${values} }` : "NULL";
        return `v${i.result.id} = (${this.type(i.result.type)}){ .data = ${data}, .length = ${i.elements.length} };`;
      }
      case "index": return `v${i.result.id} = (${op(i.array)}).data[${i.boundsCheck ? `cove_array_checked_index((size_t)(${op(i.index)}), (${op(i.array)}).length)` : `(size_t)(${op(i.index)})`}];`;
      case "arraylen": return `v${i.result.id} = (long long)(${op(i.array)}).length;`;
      case "print": {
        const value = op(i.value);
        switch (i.value.kind === "value" ? i.value.value.type : i.value.type) {
          case "String": return `printf("%s\\n", ${value});`;
          case "Bool": return `printf("%s\\n", (${value}) ? "true" : "false");`;
          case "Float": case "Double": return `printf("%g\\n", (double)(${value}));`;
          default: return `printf("%lld\\n", (long long)(${value}));`;
        }
      }
      case "return": return `return${i.value ? ` ${op(i.value)}` : ""};`;
      case "branch": return `if (${op(i.condition)}) goto ${i.thenBlock}; else goto ${i.elseBlock};`;
      case "jump": return `goto ${i.target};`;
    }
  }
  private collectArrayTypes(module: IRModule): string[] {
    const found = new Set<string>();
    const add = (type: CoveType): void => { if (/^Array<.+>$/.test(type)) found.add(type); };
    for (const fn of module.functions) {
      fn.parameters.forEach((parameter) => add(parameter.type));
      for (const block of fn.blocks) for (const instruction of block.instructions) {
        if ("result" in instruction && instruction.result) add(instruction.result.type);
        if (instruction.op === "alloca") add(instruction.result.type);
      }
    }
    return [...found].sort();
  }
  private arrayElement(type: CoveType): CoveType { return /^Array<(.+)>$/.exec(type)?.[1] ?? "Unknown"; }
  private arrayName(type: CoveType): string { return `Cove${this.arrayElement(type).replace(/[^A-Za-z0-9_]/g, "_") }Array`; }
  private arrayTypedef(type: CoveType): string { return `typedef struct ${this.arrayName(type)} { ${this.type(this.arrayElement(type))} const *data; size_t length; } ${this.arrayName(type)};`; }
  private type(type: CoveType): string { const array = /^Array<(.+)>$/.exec(type); if (array) return this.arrayName(type); switch (type) { case "Void": return "void"; case "String": return "const char *"; case "Bool": return "bool"; case "Float": return "float"; case "Double": return "double"; case "Null": return "void *"; default: return "long long"; } }
  private string(value: string): string { return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n").replace(/\r/g, "\\r").replace(/\t/g, "\\t").replace(/\0/g, "\\0")}"`; }
}
